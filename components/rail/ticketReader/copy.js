// Whole rupees without decimals; anything with paise to two places.
const rupee = (n) => {
  const v = Number(n);
  const digits = Number.isInteger(v) ? 0 : 2;
  return `₹${v.toLocaleString('en-IN', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;
};

